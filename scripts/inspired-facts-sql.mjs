// Facts (notes, gender, year, perfumers, main accords) for the "inspired by" fragrances, which have their
// own perfume page since the v5 migration.
//
//   node scripts/inspired-facts-sql.mjs
//
// Sources (all local, data-import/, collected slowly in the browser):
//   inspired-facts-queue.json            [slug, brand, name] of every inspired fragrance (the names used on the site)
//   collected-big*.json                  Fragrantica pages: { "<number>": { y, g, p, a, n } }  (+ fragrantica-image-ids.json: slug -> number)
//   collected-parfumo-inspired*.json     Parfumo pages: { "Brand|Name": { g, y, year, perfumers, accords, blocks } | { none } }
// Fragrantica wins when both know a fragrance; Parfumo fills what is still missing.
//
// Output: data-import/inspired-facts.sql for the OWNER (dry run first; after the v5 migration and
// data-import/inspired-perfumes.sql). It only fills EMPTY fields; nothing is overwritten or deleted.

import fs from 'node:fs';

const DIR = 'data-import';
const read = (f, d) => (fs.existsSync(`${DIR}/${f}`) ? JSON.parse(fs.readFileSync(`${DIR}/${f}`, 'utf8')) : d);
const readAll = prefix => Object.assign({}, ...fs.readdirSync(DIR).filter(f => f.startsWith(prefix) && f.endsWith('.json')).sort().map(f => read(f, {})));

const queue = read('inspired-facts-queue.json', []);
const ids = read('fragrantica-image-ids.json', {});
const fragrantica = readAll('collected-big');
const parfumo = readAll('collected-parfumo-inspired');

const HEADING_KEY = { top: 'top', heart: 'heart', middle: 'heart', base: 'base', 'top notes': 'top', 'middle notes': 'heart', 'heart notes': 'heart', 'base notes': 'base', notes: 'notes', '': 'notes' };
const GENDER = { women: 'female', men: 'male', 'women and men': 'unisex', female: 'female', male: 'male', unisex: 'unisex' };
// Parfumo also lists the fragrance company (Givaudan, IFF ...) among the perfumers: keep only people.
const COMPANY = /givaudan|firmenich|\biff\b|international flavors|symrise|takasago|robertet|^mane$|drom|cpl aromas/i;
const clean = s => String(s).replace(/\s+/g, ' ').trim();
const sqlText = s => `'${String(s).replace(/'/g, "''")}'`;
const sqlArray = list => `ARRAY[${list.map(sqlText).join(', ')}]::text[]`;
const pyramidOf = pairs => {
  const out = {};
  for (const [title, list] of pairs) {
    const k = HEADING_KEY[clean(title).toLowerCase()];
    const notes = (list ?? []).map(clean).filter(Boolean);
    if (k && notes.length) out[k] = [...(out[k] ?? []), ...notes];
  }
  return Object.keys(out).length ? out : null;
};

const rows = [];
let fromF = 0, fromP = 0;
for (const [slug, brand, name] of queue) {
  const f = fragrantica[ids[slug]];
  const p = parfumo[`${brand}|${name}`];
  const r = { brand, name, pyramid: null, gender: null, year: null, perfumers: null, accords: null };
  const fill = (field, value) => { if (r[field] == null && value != null && !(Array.isArray(value) && !value.length)) r[field] = value; };
  if (f && !f._404) {
    fill('pyramid', pyramidOf(Object.entries(f.n ?? {})));
    fill('gender', GENDER[f.g] ?? null);
    fill('year', f.y ?? null);
    fill('perfumers', (f.p ?? []).map(clean).filter(Boolean));
    fill('accords', (f.a ?? []).map(a => clean(a).toLowerCase()).filter(Boolean));
    fromF++;
  }
  if (p && !p.none) {
    fill('pyramid', pyramidOf(p.blocks ?? []));
    fill('gender', GENDER[p.g] ?? null);
    fill('year', p.year ?? p.y ?? null);
    fill('perfumers', (p.perfumers ?? []).map(clean).filter(x => x && !COMPANY.test(x)));
    fill('accords', (p.accords ?? []).map(a => clean(a).toLowerCase()).filter(Boolean));
    fromP++;
  }
  if (r.pyramid || r.gender || r.year || r.perfumers || r.accords) rows.push(r);
}

const values = rows.map(r => `    (${sqlText(r.brand.toLowerCase())}, ${sqlText(r.name.toLowerCase())}, ${r.pyramid ? `${sqlText(JSON.stringify(r.pyramid))}::jsonb` : 'NULL::jsonb'}, ${r.gender ? sqlText(r.gender) : 'NULL'}::text, ${r.year ?? 'NULL'}::smallint, ${r.perfumers ? sqlArray(r.perfumers) : 'NULL::text[]'}, ${r.accords ? sqlArray(r.accords) : 'NULL::text[]'})`).join(',\n');

const sql = `-- =====================================================================
-- MatchScent: notes, gender, year, perfumers and main accords of the "inspired by" fragrances
-- (generated by scripts/inspired-facts-sql.mjs, review first)
-- =====================================================================
-- Claude has NOT run this. You run it yourself in Supabase -> SQL Editor, AFTER
-- db-migrations/2026-09-v5-every-fragrance-a-page.sql and data-import/inspired-perfumes.sql.
--  * It starts as a DRY RUN (dry_run := true): it ends with a red message (EXPECTED) that says how many
--    rows it WOULD fill; nothing is saved. Then change to  dry_run := false  and run again.
--  * It only fills EMPTY fields of ${rows.length} fragrances (their perfume row, and the notes of their list entries).
--    Nothing is overwritten or deleted. All-or-nothing.
-- =====================================================================
DO $$
DECLARE
  dry_run boolean := true;   -- <<< change to false to APPLY
  n_perfumes int;
  n_dupes int;
BEGIN
  PERFORM set_config('search_path', 'public, extensions', true);

  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'dupes' AND column_name = 'inspired_perfume_id') THEN
    RAISE EXCEPTION 'STOPPED, nothing was saved. Run db-migrations/2026-09-v5-every-fragrance-a-page.sql and data-import/inspired-perfumes.sql first.';
  END IF;

  WITH v(b, n, p, g, y, pf, ac) AS (VALUES
${values || "    ('', '', NULL::jsonb, NULL::text, NULL::smallint, NULL::text[], NULL::text[])"}
  )
  UPDATE public.perfumes t
  SET note_pyramid = COALESCE(t.note_pyramid, v.p),
      gender = COALESCE(t.gender, v.g),
      year = COALESCE(t.year, v.y),
      perfumers = COALESCE(t.perfumers, v.pf),
      accords = COALESCE(t.accords, v.ac)
  FROM v WHERE lower(t.brand) = v.b AND lower(t.name) = v.n;
  GET DIAGNOSTICS n_perfumes = ROW_COUNT;

  WITH v(b, n, p) AS (VALUES
${rows.filter(r => r.pyramid).map(r => `    (${sqlText(r.brand.toLowerCase())}, ${sqlText(r.name.toLowerCase())}, ${sqlText(JSON.stringify(r.pyramid))}::jsonb)`).join(',\n') || "    ('', '', NULL::jsonb)"}
  )
  UPDATE public.dupes t SET note_pyramid = COALESCE(t.note_pyramid, v.p) FROM v WHERE lower(t.brand) = v.b AND lower(t.name) = v.n;
  GET DIAGNOSTICS n_dupes = ROW_COUNT;

  IF dry_run THEN
    RAISE EXCEPTION 'DRY RUN OK, nothing was saved. Would fill % perfumes and % list entries.', n_perfumes, n_dupes;
  END IF;
  RAISE NOTICE 'Done: % perfumes and % list entries filled.', n_perfumes, n_dupes;
END $$;
`;
fs.writeFileSync(`${DIR}/inspired-facts.sql`, sql);
console.log(`inspired-facts.sql: ${rows.length} of ${queue.length} fragrances have facts (Fragrantica ${fromF}, Parfumo ${fromP}); notes ${rows.filter(r => r.pyramid).length}, gender ${rows.filter(r => r.gender).length}, year ${rows.filter(r => r.year).length}.`);
